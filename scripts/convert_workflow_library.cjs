/* Use the installed ComfyUI frontend to serialize and round-trip real UI graphs. */
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '..');
const manifestPath = path.join(root, 'workflows/catalog.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const findings = [];

function comparable(value) {
  if (Array.isArray(value)) return value.map(comparable);
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map(k => [k, comparable(value[k])]));
  return value;
}

function differences(expected, actual) {
  const errors = [];
  for (const [id, node] of Object.entries(expected)) {
    const out = actual[id];
    if (!out || out.class_type !== node.class_type) { errors.push(`Node ${id}: class missing or changed`); continue; }
    for (const [key, value] of Object.entries(node.inputs)) {
      if (JSON.stringify(comparable(value)) !== JSON.stringify(comparable(out.inputs[key]))) errors.push(`Node ${id}: input ${key} changed`);
    }
  }
  return errors;
}

(async () => {
  const browser = await chromium.launch({executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true,
    args: ['--no-sandbox', '--disable-dev-shm-usage']});
  try {
    const page = await browser.newPage({viewport: {width: 1600, height: 1100}});
    await page.goto(process.env.COMFY_URL || 'http://127.0.0.1:8188/', {waitUntil: 'domcontentloaded'});
    await page.waitForFunction(() => window.app?.graph && window.app?.loadApiJson);
    for (const job of manifest.workflows) {
      if (job.missing_nodes.length || job.cached_archives.length) {
        job.frontend_import = {pass: false, reason: job.missing_nodes.length ? '所需节点未安装' : '依赖缓存归档，未生成可独立运行 UI'};
        findings.push({id: job.id, ...job.frontend_import});
        continue;
      }
      const graph = JSON.parse(fs.readFileSync(path.join(root, job.api), 'utf8'));
      try {
        const result = await page.evaluate(async ({graph, title, notes}) => {
          const app = window.app;
          await app.loadApiJson(graph, title);
          for (const node of app.graph._nodes) {
            for (const widget of node.widgets || []) {
              if (widget.name === 'control_after_generate') widget.value = 'fixed';
              // MOSS's structured layout is literal JSON. Comfy's dynamic prompt
              // parser otherwise strips its braces. Escaping is a UI-only change:
              // both queue exports below must still match the original API text.
              if (widget.dynamicPrompts && typeof widget.value === 'string' && widget.value.trim().startsWith('{')) {
                try { JSON.parse(widget.value); widget.value = widget.value.replace(/[{}]/g, '\\$&'); } catch (_) {}
              }
            }
            if ((node.widgets || []).some(w => w.name === 'prompt' || w.name === 'text')) node.size = [420, Math.max(node.size[1], 310)];
          }
          if (app.graph.arrange) app.graph.arrange(110);
          const original = (await app.graphToPrompt()).output;
          const ui = app.graph.serialize();
          // Frontend-only note: it has no backend node and cannot enqueue work.
          const noteId = Math.max(0, ...ui.nodes.map(n => typeof n.id === 'number' ? n.id : 0)) + 1;
          ui.nodes.push({id: noteId, type: 'Note', pos: [100, -360], size: [1600, 360], flags: {}, order: -1, mode: 0,
            inputs: [], outputs: [], properties: {}, widgets_values: [notes], color: '#25394d', bgcolor: '#344b60', title: '使用说明 · 平台 / 配方 / 输入'});
          ui.last_node_id = Math.max(ui.last_node_id || 0, noteId);
          const minX = Math.min(...ui.nodes.map(n => n.pos[0]));
          const minY = Math.min(...ui.nodes.map(n => n.pos[1]));
          const maxX = Math.max(...ui.nodes.map(n => n.pos[0] + n.size[0]));
          const maxY = Math.max(...ui.nodes.map(n => n.pos[1] + n.size[1]));
          const scale = Math.min(0.8, 1320 / (maxX - minX + 160), 900 / (maxY - minY + 160));
          ui.extra ||= {};
          ui.extra.ds = {scale, offset: [80 / scale - minX, 80 / scale - minY]};
          ui.extra.model_feature_library = {title, note: 'UI format generated by ComfyUI itself; round-trip checked without model execution'};
          await app.loadGraphData(ui, true, true);
          const roundTrip = (await app.graphToPrompt()).output;
          return {ui, original, roundTrip, missing: app.graph._nodes.filter(n => n.has_errors).map(n => n.type)};
        }, {graph, title: job.title, notes: job.notes});
        const errors = [...differences(graph, result.original), ...differences(graph, result.roundTrip),
          ...result.missing.map(n => 'Missing UI node ' + n)];
        if (errors.length) {
          job.frontend_import = {pass: false, reason: '前端回环参数或连线不一致', errors};
        } else {
          const filename = path.join(root, job.ui);
          fs.mkdirSync(path.dirname(filename), {recursive: true});
          fs.writeFileSync(filename, JSON.stringify(result.ui, null, 2) + '\n');
          job.frontend_import = {pass: true, node_count: result.ui.nodes.length, original_inputs_preserved: true,
            fixed_seed_controls: true, note: '导入/导出通过；不是模型执行通过'};
        }
      } catch (error) {
        job.frontend_import = {pass: false, reason: String(error.message)};
      }
      findings.push({id: job.id, ...job.frontend_import});
      console.log(job.id, job.frontend_import.pass ? 'UI_PASS' : 'BLOCKED', job.frontend_import.errors?.join('; ') || job.frontend_import.reason || '');
    }
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
    fs.writeFileSync(path.join(root, 'trials/2026-10-24-platform-report/frontend-conversion.json'), JSON.stringify(findings, null, 2) + '\n');
    console.log(JSON.stringify({total: findings.length, passed: findings.filter(f => f.pass).length, blocked: findings.filter(f => !f.pass).length}));
  } finally { await browser.close(); }
})().catch(error => {console.error(error); process.exitCode = 1;});
